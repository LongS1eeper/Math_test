"""수식 비교기 검증.  python test_mathcmp.py"""
import mathcmp as M

OK = FAIL = 0


def same(correct, given, note=""):
    global OK, FAIL
    r = M.equal(correct, given)
    if r is True:
        OK += 1
    else:
        FAIL += 1
        print(f" FAIL 같아야 함: {correct!r} vs {given!r} → {r}  {note}")


def diff(correct, given, note=""):
    global OK, FAIL
    r = M.equal(correct, given)
    if r is False:
        OK += 1
    else:
        FAIL += 1
        print(f" FAIL 달라야 함: {correct!r} vs {given!r} → {r}  {note}")


def manual(correct, given="아무거나", note=""):
    global OK, FAIL
    r = M.equal(correct, given)
    if r is None:
        OK += 1
    else:
        FAIL += 1
        print(f" FAIL 판정불가여야 함: {correct!r} vs {given!r} → {r}  {note}")


# ---------------------------------------------------------------- 숫자
same("138", "138")
same("138", " 138 ")
diff("138", "183")
same("17/2", "8.5")
same("100/3", "100/3")
diff("100/3", "33")
same("-10", "−10")
same("240", "240.0")

# ---------------------------------------------------------------- 무리수
same("2√7", "2root7")
same("2√7", "2sqrt7")
same("2√7", "2*sqrt(7)")
same("2√7", "sqrt(28)")
same("2√7", "2루트7")
same("2√7", "5.291502622129181")
diff("2√7", "2√5")
same("5√5", "sqrt(125)")
same("2√3", "√12")
same("(5+5√2)/2", "(5+5*sqrt(2))/2")
same("27/2", "13.5")
same("π", "pi")
same("π", "파이")

# ---------------------------------------------------------------- 좌표
same("(4,4)", "(4, 4)")
same("(4,4)", "( 4 , 4 )")
diff("(4,4)", "(4,5)")
same("(4,4)", "(8/2, 2*2)")

# ---------------------------------------------------------------- 라벨
same("a=-1, b=-1, c=3", "b=-1, a=-1, c=3", "순서 무관")
same("a=-1, b=-1, c=3", "a = -1, b = -1, c = 3")
diff("a=-1, b=-1, c=3", "a=-1, b=-1, c=4")
same("a=8, b=3√5", "a=8, b=3root5")
same("a=-2, b=-5, c=9", "a=-2,b=-5,c=9")
diff("a=8, b=3√5", "a=8, b=3√6")

# ---------------------------------------------------------------- 좌표 묶음
same("(0,-2), (0,-10)", "(0,-10), (0,-2)", "순서 무관")
same("(12,5), (2,5), (4,-1), (-6,-1)", "(-6,-1), (4,-1), (2,5), (12,5)")
diff("(0,-2), (0,-10)", "(0,-2), (0,-11)")
diff("(0,-2), (0,-10)", "(0,-2)")

# ---------------------------------------------------------------- 방정식
same("y=2x-5", "y = 2x - 5")
same("y=2x-5", "2x-y-5=0")
same("y=2x-5", "y-2x+5=0")
same("y=2x-5", "4x-2y=10")
diff("y=2x-5", "y=2x+5")
diff("y=2x-5", "y=3x-5")
same("(x-4)²+(y-2)²=1", "x²+y²-8x-4y+19=0")
same("(x-4)^2+(y-2)^2=1", "(x-4)**2+(y-2)**2=1")
diff("(x-4)²+(y-2)²=1", "(x-4)²+(y-2)²=4")
same("y=(3/4)x", "4y=3x")
same("y=(3/4)x", "y=0.75x")

# ---------------------------------------------------------------- 비
same("1:2", "2:4")
diff("1:2", "1:3")
same("AP:BP=1:2", "AP:BP = 2:4")

# ---------------------------------------------------------------- 소문항
same("(1) 17/2  (2) y=(3/4)x", "(1) 8.5 (2) 3x-4y=0")
same("(1) 6  (2) π", "(1) 6 (2) pi")
diff("(1) 6  (2) π", "(1) 7 (2) pi")

# ---------------------------------------------------------------- 문자식
same("2ar/k", "2*a*r/k")
same("AB=2ar/k", "AB = 2ar/k")
diff("2ar/k", "2ar/m")

# ---------------------------------------------------------------- 판정 불가
manual("y=mx±r√(m²+1)", "y=mx+r√(m²+1)", "± 는 사람이")
manual("서술형 (풀이 과정 서술)")
manual("P(3/4,3/4), Q(12/7,12/7), 최솟값 5+√10", "아무거나", "한글 섞임")

# ---------------------------------------------------------------- 무응답·오입력
diff("138", "")
diff("138", "   ")
if M.equal("138", "몰라요") is not None:
    print(" FAIL 한글 답은 판정 불가여야 함")
    FAIL += 1
else:
    OK += 1

# ---------------------------------------------------------------- 안전성
for bad in ["__import__('os')", "open('/etc/passwd')", "1;print(1)", "((((", "2**999999"]:
    r = M.equal("138", bad)
    if r in (False, None):
        OK += 1
    else:
        FAIL += 1
        print(f" FAIL 위험 입력이 정답 처리됨: {bad!r}")

# ---------------------------------------------------------------- 입력 안내
for a in ["138", "(4,4)", "a=-1, b=-1, c=3", "y=2x-5", "1:2", "2ar/k",
          "(0,-2), (0,-10)", "서술형 (풀이 과정 서술)"]:
    h = M.hint(a)
    if not h:
        FAIL += 1
        print(f" FAIL 안내문 없음: {a}")
    else:
        OK += 1

# ---------------------------------------------------------------- 라벨 생략
same("a=8", "8", "라벨 없이 값만")
same("y=2x-5", "2x-y-5=0")
same("a=8, b=3√5", "8, 3root5", "라벨 없이 순서대로")
same("(1) AP:BP=1:2  (2) (x+2)²+y²=16", "(1) 1:2 (2) x²+4x+y²-12=0")
diff("a=8, b=3√5", "3√5, 8", "순서가 다르면 오답")

# ---------------------------------------------------------------- 실제 정답 표기 변형
same("(x-4)²+(y-2)²=1", "x^2+y^2-8x-4y+19=0")
same("(x+2)²+y²=16", "x²+4x+y²-12=0")
same("P=(3/4,3/4), Q=(12/7,12/7), min=5+√10", "P=(0.75,0.75), Q=(12/7,12/7), min=5+root10")
same("AB=2ar/k", "AB=2*a*r/k")
same("(12,5), (2,5), (4,-1), (-6,-1)", "(2,5), (12,5), (-6,-1), (4,-1)")
diff("100/3", "33.33")
same("100/3", "33.333333333333336")


print(f"\n통과 {OK} / 실패 {FAIL}")
raise SystemExit(1 if FAIL else 0)
